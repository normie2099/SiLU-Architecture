#!/usr/bin/env python3
"""
synth2gem5.py - turn a synthesis timing result into the gem5 latency of the custom operation.

The rule (iron law, clock-period term):   cycles = ceil(data_delay / clock_period)

Input  : the data delay of the SiLU unit, either read from a Quartus timing report text file
         (--report) or given directly (--delay-ns). Every run records where the number came from.
Output : a JSON file with, for each core clock, the latency in cycles, plus a small gem5 include
         file per clock that sets the op latency. Nothing here is typed by hand.

Usage
  python scripts/synth2gem5.py --report quartus/output_files/silu.sta.rpt --clocks 50 100 200 500 1000
  python scripts/synth2gem5.py --delay-ns 8.058 --clocks 50 100 123 200 500 1000 --pipeline-stages 1 2 3

--pipeline-stages models a unit split into N equal stages: each stage then has delay/N (plus an optional
--stage-overhead-ns for the register), and the instruction has latency N cycles but throughput of 1 per
cycle if the clock fits. The effective cycle count per stage is ceil(stage_delay / period).
"""
import argparse, json, math, pathlib, re, sys

# Quartus timing reports print the path delay in several ways. Try the common ones; if none match,
# the user must pass --delay-ns (and the script says so instead of guessing).
PATTERNS = [
    r"Data Arrival Time\s*[:;|]*\s*([0-9.]+)",
    r"Data Delay\s*[:;|]*\s*([0-9.]+)",
    r";\s*Data Delay\s*;\s*([0-9.]+)\s*;",
    r"data delay\s*[=:]\s*([0-9.]+)",
]


def read_delay(path):
    text = pathlib.Path(path).read_text(errors="replace")
    for pat in PATTERNS:
        m = re.findall(pat, text, flags=re.I)
        if m:
            vals = [float(v) for v in m]
            return max(vals), f"{path} (pattern {pat!r}, {len(vals)} matches, worst {max(vals)} ns)"
    sys.exit(f"No delay found in {path}. Open the report, find the worst data path delay, and pass --delay-ns.")


def cycles(delay_ns, clock_mhz, stage_overhead_ns=0.0, stages=1):
    period = 1000.0 / clock_mhz
    stage_delay = delay_ns / stages + (stage_overhead_ns if stages > 1 else 0.0)
    per_stage = max(1, math.ceil(stage_delay / period - 1e-9))
    return per_stage * stages, per_stage


def min_stages(delay_ns, clock_mhz, stage_overhead_ns=0.3):
    """Fewest pipeline stages N such that delay/N + register overhead fits in one clock period (N=1 needs no overhead)."""
    period = 1000.0 / clock_mhz
    if delay_ns <= period:
        return 1
    return math.ceil(delay_ns / (period - stage_overhead_ns) - 1e-9)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--report")
    g.add_argument("--delay-ns", type=float)
    ap.add_argument("--clocks", type=float, nargs="+", required=True, help="core clocks in MHz")
    ap.add_argument("--pipeline-stages", type=int, nargs="+", default=[1])
    ap.add_argument("--stage-overhead-ns", type=float, default=0.3,
                    help="register overhead added per stage when stages > 1 (document your choice)")
    ap.add_argument("--out", default="results/raw/latency_table.json")
    ap.add_argument("--gem5-dir", default="gem5/generated")
    a = ap.parse_args()

    if a.report:
        delay, source = read_delay(a.report)
    else:
        delay, source = a.delay_ns, "command line --delay-ns"

    rows = []
    for stages in a.pipeline_stages:
        for mhz in a.clocks:
            lat, per = cycles(delay, mhz, a.stage_overhead_ns, stages)
            rows.append({"stages": stages, "clock_mhz": mhz, "period_ns": round(1000 / mhz, 3),
                         "latency_cycles": lat, "cycles_per_stage": per,
                         "single_cycle_ok": lat == 1})
    out = {"delay_ns": delay, "delay_source": source, "stage_overhead_ns": a.stage_overhead_ns, "rows": rows}
    p = pathlib.Path(a.out); p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(out, indent=2))

    gd = pathlib.Path(a.gem5_dir); gd.mkdir(parents=True, exist_ok=True)
    for r in rows:
        name = f"silu_lat_{r['stages']}stage_{int(r['clock_mhz'])}MHz.py"
        (gd / name).write_text(
            f"# generated by synth2gem5.py from {source}\n"
            f"SILU_OP_LATENCY = {r['latency_cycles']}   # cycles at {r['clock_mhz']} MHz, {r['stages']} stage(s)\n"
            f"SILU_OP_ISSUE_LAT = {1 if r['stages'] > 1 else r['latency_cycles']}\n")
    print(f"delay {delay} ns from {source}")
    print("stages clock_MHz  period_ns  latency_cycles")
    for r in rows:
        print(f"{r['stages']:>6} {r['clock_mhz']:>9} {r['period_ns']:>10} {r['latency_cycles']:>14}")
    print(f"wrote {p} and {len(rows)} files in {gd}")


if __name__ == "__main__":
    main()
