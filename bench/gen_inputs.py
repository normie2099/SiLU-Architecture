#!/usr/bin/env python3
"""Generate bench/inputs.h: N raw Q6.10 inputs. Default: uniform grid over [-4, 4) (raw -4096..4095).
Optionally replay real activations saved by the model scripts (a .npy of int16 raw values)."""
import argparse, numpy as np, pathlib
ap = argparse.ArgumentParser()
ap.add_argument("--n", type=int, default=1024)
ap.add_argument("--real", help="optional .npy of raw int16 activations to replay (first N used)")
ap.add_argument("--out", default=str(pathlib.Path(__file__).with_name("inputs.h")))
a = ap.parse_args()
if a.real:
    v = np.load(a.real).astype(np.int64).ravel()[:a.n]
    kind = f"real activations from {a.real}"
else:
    v = np.linspace(-4096, 4095, a.n).round().astype(np.int64)
    kind = "uniform grid over raw -4096..4095 (real -4..+4)"
assert len(v) == a.n, "not enough values"
with open(a.out, "w") as f:
    f.write(f"/* generated by gen_inputs.py: {kind} */\n#define N_INPUTS {a.n}\n")
    f.write("static const short silu_in[N_INPUTS] = {\n")
    f.write(",".join(str(int(x)) for x in v)); f.write("\n};\n")
print(f"wrote {a.out}: {a.n} inputs, {kind}")
