#!/usr/bin/env python3
"""Generate bench/silu_table.h: 257-entry Q6.10 table of exact SiLU over [-4, 4] (step 32 raw units = 1/32),
used by the lookup-table baseline with linear interpolation."""
import numpy as np, pathlib
raw = np.arange(-4096, 4096 + 1, 32)               # 257 points
x = raw / 1024.0
y = np.round(x / (1 + np.exp(-x)) * 1024).astype(int)
out = pathlib.Path(__file__).with_name("silu_table.h")
out.write_text("/* generated by gen_table.py: exact SiLU, Q6.10, 257 entries over [-4,4], step 32 raw */\n"
               "static const short silu_tab[257] = {\n" + ",".join(map(str, y)) + "\n};\n")
print(f"wrote {out}")
